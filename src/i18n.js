// keys: { mod, alt, mac } for the platform the page runs on.
export function helpText(lang, keys) {
  const or = lang === 'fr' ? ' ou ' : ' or ';
  const redoKeys = keys.mac ? `\`${keyLabel('Shift-Mod-z', keys, lang)}\`` : `\`Ctrl+Y\`${or}\`${keyLabel('Ctrl-Shift-z', keys, lang)}\``;
  // Help is on F1 and on Shift+Cmd/Ctrl+I everywhere. Off a Mac, Ctrl+Shift+I is the browsers' developer
  // tools too; the app claims it, and names it, so that a test on Windows shows whether the page gets it.
  const helpKeys = `\`F1\`${or}\`${keyLabel(SHORTCUTS.help, keys, lang)}\``;
  // {win:…} is kept off a Mac and dropped on one, so Help only ever names the keys of the platform it is
  // being read on.
  let text = (HELP[lang] || HELP.en).join('\n').replaceAll('{redoKeys}', redoKeys).replaceAll('{helpKeys}', helpKeys)
    .replace(/\{win:([^}]*)\}/g, (_, w) => (keys.mac ? '' : w))
    .replace(/\{key:([^}]+)\}/g, (_, k) => keyLabel(SHORTCUTS[k] || k, keys, lang))
    .replaceAll('{mod}', keys.mod).replaceAll('{alt}', keys.alt).replaceAll('{version}', APP_VERSION) + '\n';
  // French typography: narrow no-break space before ; ! ?, no-break space before : and » and after «.
  if (lang === 'fr') text = text.replace(/ ([;!?])/g, NNB + '$1').replace(/ ([:»])/g, NB + '$1').replace(/« /g, '«' + NB);
  return text;
}
