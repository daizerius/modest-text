const KEY_NAMES = { ArrowUp: '↑', ArrowDown: '↓', ArrowLeft: '←', ArrowRight: '→' };
// "⇧⌘X" / "⌥⌘1" on a Mac, as its menus write them (⌃ Control, ⌥ Option, ⇧ Shift, ⌘ Command, in that order,
// with the Mac's ↩ return and ⌫ delete keys); "Ctrl+Shift+X" elsewhere, in the interface language.
// The punctuation keys are named as this keyboard prints them, since they are matched by physical position:
// on a French AZERTY keyboard "Cmd+]" is written "Cmd+$", because that is the key to press (see keys.js).
export function keyLabel(spec, keys, lang) {
  const s = typeof spec === 'string' ? spec : keys.mac ? spec.mac : spec.win;
  const parts = s.split('-');
  const key = parts.pop();
  const mods = new Set(parts.map((p) => (p === 'Mod' ? (keys.mac ? 'Cmd' : 'Ctrl') : p === 'Meta' ? 'Cmd' : p)));
  const names = keys.mac ? { Ctrl: '⌃', Alt: '⌥', Shift: '⇧', Cmd: '⌘' } : { Ctrl: 'Ctrl', Alt: 'Alt', Shift: lang === 'fr' ? 'Maj' : 'Shift' };
  const order = keys.mac ? ['Ctrl', 'Alt', 'Shift', 'Cmd'] : ['Ctrl', 'Alt', 'Shift'];
  const local = keys.mac ? { Enter: '↩', Backspace: '⌫', Delete: '⌦', Escape: lang === 'fr' ? 'Échap' : 'Esc' }
    : lang === 'fr' ? { Enter: 'Entrée', Space: 'Espace', Delete: 'Suppr', Backspace: 'Retour arrière', Escape: 'Échap' }
      : { Enter: 'Enter', Escape: 'Esc' };
  if (lang === 'fr' && keys.mac) local.Space = 'Espace';
  const name = KEY_NAMES[key] || local[key] || (key === 'Minus' ? keyFace('-') : key.length === 1 ? keyFace(key).toUpperCase() : key);
  const mod = order.filter((m) => mods.has(m)).map((m) => names[m]);
  return keys.mac ? mod.join('') + name : [...mod, name].join('+');
}

