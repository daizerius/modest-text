// keys: the platform's key names, e.g. { mod: 'Cmd', alt: 'Option' } on a Mac, { mod: 'Ctrl', alt: 'Alt' } elsewhere;
// they fill {mod} and {alt} in every string.
export function makeT(lang, keys = {}) {
  const dict = STRINGS[lang] || STRINGS.en;
  const nf = new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : 'en-US');
  const fill = (s, vars) => s.replace(/\{(\w+)\}/g, (_, k) => (vars && k in vars ? String(vars[k]) : k in keys ? keys[k] : `{${k}}`));
  const t = (key, vars) => {
    const s = dict[key];
    if (s === undefined) return key;
    if (Array.isArray(s)) {
      const n = vars?.n ?? 0;
      const idx = lang === 'fr' ? (n >= 2 ? 1 : 0) : (n === 1 ? 0 : 1);
      return fill(s[idx], { ...vars, n: nf.format(n) });
    }
    return fill(s, vars);
  };
  t.num = (n) => nf.format(n);
  // Label of a named shortcut (SHORTCUTS) or of a key spec, e.g. t.key('bold') -> "Cmd+B".
  t.key = (name) => keyLabel(SHORTCUTS[name] || name, keys, lang);
  t.lang = lang;
  return t;
}

